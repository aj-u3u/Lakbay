import '../models/trip.dart';

class GeminiService {
  // Simulates an AI request to Gemini for generating a customized travel itinerary
  Future<Trip> generateItinerary({
    required String destinationDistrict, // e.g. 'Davao City', 'Davao Oriental', 'Davao del Norte'
    required int durationDays,
    required String travelVibe, // e.g. 'nature', 'beach', 'urban', 'adventure'
    required double budgetLimit,
  }) async {
    // Simulate network delay representing the LLM processing time
    await Future.delayed(const Duration(milliseconds: 2500));

    // Construct custom itineraries programmatically based on user selections
    String title = 'AI-Customized $travelVibe Expedition';
    String destinationName = '$destinationDistrict, Davao Region';
    String image = 'https://images.unsplash.com/photo-1470071459604-3b5ec3a7fe05?w=800&q=80';

    if (destinationDistrict.contains('Norte') || destinationDistrict.contains('Samal')) {
      image = 'https://images.unsplash.com/photo-1507525428034-b723cf961d3e?w=800&q=80';
      title = 'Gemini Tailored Samal Sun & Sea Itinerary';
      destinationName = 'Samal Island, Davao del Norte';
    } else if (destinationDistrict.contains('Oriental') || destinationDistrict.contains('Mati')) {
      image = 'https://images.unsplash.com/photo-1506929562872-bb421503ef21?w=800&q=80';
      title = 'Gemini Custom Dahican Beach Surf & Turf';
      destinationName = 'Mati City, Davao Oriental';
    } else if (destinationDistrict.contains('City') || destinationDistrict.contains('Davao City')) {
      image = 'https://images.unsplash.com/photo-1441974231531-c6227db76b6e?w=800&q=80';
      title = 'Gemini Davao City Eco & Urban Explorer';
      destinationName = 'Davao City Proper';
    }

    // Build day-to-day agenda
    final Map<int, List<TripActivity>> generatedAgenda = {};

    for (int day = 1; day <= durationDays; day++) {
      generatedAgenda[day] = [
        TripActivity(
          time: '08:30 AM',
          title: 'Day $day Breakfast & Briefing',
          description: 'Start with local breakfast delicacies and orient with your digital travel route.',
          cost: '₱200 (approximate)',
          location: 'Davao Region Local Cafe',
        ),
        TripActivity(
          time: '10:30 AM',
          title: day == 1 ? 'Primary Landmark Exploration' : 'Scenic Highland Outdoor Visit',
          description: 'Experience immersive eco-trails and culture highlights. Remember to respect native guides.',
          cost: '₱150 - ₱300',
          location: destinationName,
        ),
        TripActivity(
          time: '03:00 PM',
          title: 'Afternoon $travelVibe Activity',
          description: 'A customized, AI-recommended activity based on your $travelVibe preferences.',
          cost: '₱250',
          location: destinationName,
        ),
        TripActivity(
          time: '07:00 PM',
          title: 'Premium Culinary Experience',
          description: 'Savor regional seafood grills, local fresh fruits, and premium dining spots.',
          cost: '₱400 (approximate)',
          location: 'Local Food District',
        ),
      ];
    }

    return Trip(
      id: 'ai-trip-${DateTime.now().millisecondsSinceEpoch}',
      title: title,
      destinationName: destinationName,
      dateRange: 'Flexible (Generated by Gemini)',
      budget: budgetLimit,
      imageUrl: image,
      itinerary: generatedAgenda,
    );
  }
}
