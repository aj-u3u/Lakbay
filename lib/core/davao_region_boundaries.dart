    regionCoordinates.forEach((regionName, polyRings) {
      final color = regionColors[regionName] ?? Colors.grey;
      for (final ring in polyRings) {
        polygons.add(
          Polygon(
            points: ring,
            color: color.withValues(alpha: fillAlpha),
            borderColor: color,
            borderStrokeWidth: strokeWidth,
          ),
        );
      }
    });
    return polygons;
