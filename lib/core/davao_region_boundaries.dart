  static Color getRegionColor(String? districtName) {
    if (districtName == null) return Colors.red;
    final dist = districtName.toLowerCase().trim();

    if (dist.contains('davao de oro') ||
        dist.contains('oro') ||
        dist.contains('compostela')) {
      return Colors.amber; // Davao de Oro
    } else if (dist.contains('davao del norte') || dist.contains('norte')) {
      return Colors.blue; // Davao del Norte
    } else if (dist.contains('davao oriental') || dist.contains('oriental')) {
      return Colors.deepOrange; // Davao Oriental
    } else if (dist.contains('davao occidental') ||
        dist.contains('occidental')) {
      return Colors.purple; // Davao Occidental
    } else if (dist.contains('davao del sur') || dist.contains('sur')) {
      return Colors.green; // Davao del Sur
    } else if (dist.contains('davao city') || dist.contains('davao')) {
      return Colors.teal; // Davao City
    }
    return Colors.teal;
  }

